import assert from 'node:assert/strict';
import {readFileSync, readdirSync} from 'node:fs';
import {join} from 'node:path';
const text=path=>readFileSync(path,'utf8');
const html=text('index.html'), js=text('src/app.js'), css=text('styles.css');
const nav=text('src/core/navigation.js'), screens=text('src/views/screens.js'), allJs=js+nav+screens;
const manifest=JSON.parse(text('manifest.webmanifest'));
const required=['index.html','styles.css','src/app.js','manifest.webmanifest','SECURITY.md','docs/API_CONTRACT.md','docs/UAT.md','.gitignore'];
for(const f of required)assert.ok(text(f).length>0,'Missing file '+f);
assert.match(html,/Content-Security-Policy/);
assert.match(html,/id="sideNav"/);
assert.match(html,/id="mobileNav"/);
assert.match(html,/id="loginDialog"/);
assert.match(html,/id="openLogin"/);
assert.match(html,/id="pageEyebrow"/);
assert.match(allJs,/data-filter/);
assert.match(allJs,/stat-value/);
assert.match(html,/disabled/);
assert.match(allJs,/ROUTES/);
for (const route of ['beranda','pelanggan','tagihan','pembayaran','kas','mikrotik','audit','pengaturan'])assert.ok(allJs.includes("id:'"+route+"'"),'Missing route '+route);
assert.ok(!allJs.includes('localStorage')&&!allJs.includes('sessionStorage'),'No browser token storage until auth design reviewed');
assert.ok(!/fetch\s*\(/.test(allJs),'No API requests until backend auth validated');
assert.ok(!/google\.com\/spreadsheets\/d\//.test(allJs+html),'Private database cannot be embedded');
assert.ok(!/TM_HASH_PEPPER|TM_DB_ID|FONNTE_TOKEN|MIKROTIK_PASSWORD/.test(js+html),'No privileged config');
assert.match(css,/\.mobile-nav/);
assert.match(css,/#FAFAFC/);
assert.match(css,/#FFD25E/);
assert.match(css,/\.hero/);
assert.match(css,/\.sidebar/);
assert.match(css,/\.mobile-nav/);
assert.ok(!html.includes('ngulik-inspired.css')&&!html.includes('sunlime-mobile.css'));
const sw=text('sw.js');
assert.match(sw,/const PUBLIC_FILES=/);
assert.match(sw,/req.method!=="GET"/);
assert.match(sw,/allowed.has\(path\)/);
assert.match(sw,/url.search/);


assert.ok(!/\/api\//.test(sw),'Service worker must never cache API paths');
assert.match(js,/serviceWorker\.register/);
assert.match(html,/type="module"/);
assert.match(html,/\.\/styles\.css/);
assert.ok(sw.includes('src/core/navigation.js')&&sw.includes('src/views/screens.js'));
const contract=text('docs/API_CONTRACT.md');
for(const key of ['action','session_token','text/plain;charset=utf-8','SUCCESS','ERROR','LockService.getScriptLock()'])assert.ok(contract.includes(key));
assert.match(html,/id="offlineNotice"/);
assert.equal(manifest.start_url,'./');
assert.equal(manifest.scope,'./');
